  function iconeTema() { return temaAtual() === 'dark' ? ICONES.sol : ICONES.lua; }

  function alternarTema() {
    const novo = temaAtual() === 'dark' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', novo);
    gravarTema(novo);
    document.querySelectorAll('[data-acao="tema"]').forEach(b => {
      b.innerHTML = iconeTema();
      b.setAttribute('aria-label', novo === 'dark' ? 'Usar tema claro' : 'Usar tema escuro');
    });
  }

  function prepararBotoesTema() {
    document.querySelectorAll('[data-acao="tema"]').forEach(b => {
      b.innerHTML = iconeTema();
      b.setAttribute('aria-label', temaAtual() === 'dark' ? 'Usar tema claro' : 'Usar tema escuro');
      b.addEventListener('click', alternarTema);
    });
  }

  // ---------- Supabase ----------
  let sb = null;
  if (window.supabase && window.supabase.createClient) {
    sb = window.supabase.createClient(cfg.SUPABASE_URL, cfg.SUPABASE_PUBLISHABLE_KEY, {
      auth: { persistSession: true, autoRefreshToken: true, detectSessionInUrl: true }
    });
  }

  // Garante que só usuário logado e ativo acessa a página.
  // Retorna { usuario, perfil } ou redireciona para o login.
  async function exigirLogin() {
    if (!sb) { window.location.replace('index.html'); return null; }
    const { data: { session } } = await sb.auth.getSession();
    if (!session) { window.location.replace('index.html'); return null; }

    const { data: perfil, error } = await sb
      .from('perfis')
      .select('id, nome, email, papel, ativo')
      .eq('id', session.user.id)
      .maybeSingle();

    if (error || !perfil || !perfil.ativo) {
      await sb.auth.signOut();
      window.location.replace('index.html?motivo=inativo');
      return null;
    }
    return { usuario: session.user, perfil };
  }

  async function sair() {
    if (sb) await sb.auth.signOut();
    window.location.replace('index.html');
  }

  function escapar(txt) {
    return String(txt ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  }

  window.Radar = { sb, ICONES, exigirLogin, sair, escapar, prepararBotoesTema, config: cfg };
  document.addEventListener('DOMContentLoaded', prepararBotoesTema);
